#!/usr/bin/env python3
"""Generate/check the development-helper pins from pyproject dependency declarations.

pyproject.toml owns the dependency names and constraints. This generated
environment snapshot supplies exact versions to the existing development-helper cache.
Regenerate only from an approved, tested Python 3.12 environment.
"""
from __future__ import annotations

import argparse
from importlib import metadata
from pathlib import Path
import re
import sys
import tomllib

from pip._vendor.packaging.requirements import Requirement
from pip._vendor.packaging.markers import default_environment
from pip._vendor.packaging.version import Version

ROOT = Path(__file__).resolve().parents[1]
PROJECT = ROOT / "pyproject.toml"
OUTPUT = ROOT / "requirements-dev.txt"
HEADER = (
    "# GENERATED by scripts/sync_requirements_dev.py from pyproject.toml.\n"
    "# Dependency declarations belong in pyproject.toml; do not hand-edit this file.\n"
    "# Pin versions reflect the reviewed Python 3.12 validation environment.\n"
)


def normalize(value: str) -> str:
    return re.sub(r"[-_.]+", "-", value).lower()


def requirements() -> dict[str, Requirement]:
    source = tomllib.loads(PROJECT.read_text(encoding="utf-8"))
    declarations = (
        source["project"]["dependencies"]
        + source["project"]["optional-dependencies"]["dev"]
        + source["build-system"]["requires"]
    )
    result: dict[str, Requirement] = {}
    for item in declarations:
        requirement = Requirement(item)
        name = normalize(requirement.name)
        if requirement.marker or requirement.url or requirement.extras:
            raise ValueError(f"Unsupported conditional development requirement: {name}")
        if name in result:
            raise ValueError(f"Duplicate pyproject dependency: {name}")
        result[name] = requirement
    return result


def resolved_closure() -> dict[str, str]:
    """Expand runtime/dev/build requirements using installed distribution metadata.

    The development-helper dependency cache installs exact pins with --no-deps.
    Thus the manifest must contain every reachable wheel, including extras
    (e.g. the cryptography dependencies requested by pyjwt[crypto]).
    """
    roots = requirements()
    constraints: dict[str, list[Requirement]] = {
        name: [item] for name, item in roots.items()
    }
    requested_extras: dict[str, set[str]] = {name: set() for name in roots}
    visited: dict[str, frozenset[str]] = {}
    pins: dict[str, str] = {}
    pending = list(roots)
    # Vendored packaging type annotations differ between pip releases.
    # Normalize once to stable strings before merging marker extras.
    markers: dict[str, str] = {
        str(key): str(value) for key, value in default_environment().items()
    }

    while pending:
        name = pending.pop()
        dist = metadata.distribution(name)
        version = dist.version
        for requirement in constraints[name]:
            if requirement.specifier and Version(version) not in requirement.specifier:
                raise ValueError(
                    f"Installed {name}=={version} violates {requirement.specifier}"
                )
        pins[name] = version
        extras = frozenset(requested_extras[name])
        if visited.get(name) == extras:
            continue
        visited[name] = extras
        for raw in dist.requires or ():
            requirement = Requirement(raw)
            if requirement.marker and not any(
                requirement.marker.evaluate({**markers, "extra": extra})
                for extra in ("", *sorted(extras))
            ):
                continue
            if requirement.url:
                raise ValueError("Development lock disallows direct URLs")
            dependency = normalize(requirement.name)
            constraints.setdefault(dependency, []).append(requirement)
            before = set(requested_extras.get(dependency, ()))
            requested_extras.setdefault(dependency, set()).update(requirement.extras)
            if dependency not in visited or requested_extras[dependency] != before:
                pending.append(dependency)
            else:
                # Even when already visited, a newly discovered constraint
                # must still be checked against the previously selected wheel.
                if (requirement.specifier
                        and Version(pins[dependency]) not in requirement.specifier):
                    raise ValueError(
                        f"Installed {dependency}=={pins[dependency]} "
                        f"violates {requirement.specifier}"
                    )
    return pins


def parse_pins() -> dict[str, str]:
    result: dict[str, str] = {}
    if not OUTPUT.is_file():
        raise ValueError("Missing generated requirements-dev.txt")
    for item in OUTPUT.read_text(encoding="utf-8").splitlines():
        line = item.strip()
        if not line or line.startswith("#"):
            continue
        match = re.fullmatch(r"([a-z0-9][a-z0-9-]*)==([0-9][a-zA-Z0-9.+!-]*)", line)
        if match is None or match[1] in result:
            raise ValueError("Invalid or duplicate pinned development dependency")
        result[match[1]] = match[2]
    return result


def render(pins: dict[str, str]) -> str:
    return HEADER + "".join(f"{name}=={pins[name]}\n" for name in sorted(pins))


def check() -> None:
    pins = parse_pins()
    required = resolved_closure()
    if pins.keys() != required.keys():
        missing = sorted(required.keys() - pins.keys())
        extra = sorted(pins.keys() - required.keys())
        raise ValueError(f"Development pin closure mismatch: missing={missing}, extra={extra}")
    for name, version in required.items():
        if pins[name] != version:
            raise ValueError(
                f"Installed {name}=={version} differs from pinned {pins[name]}"
            )
    if OUTPUT.read_text(encoding="utf-8") != render(pins):
        raise ValueError("Development pins are not in canonical generated format")


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--write", action="store_true",
                        help="Refresh from current installed versions (review before commit)")
    parser.add_argument("--pin", action="append", default=[], metavar="NAME==VERSION",
                        help="Override absent/selected installed build-tool version on --write")
    args = parser.parse_args(argv)
    try:
        if args.write:
            overrides: dict[str, str] = {}
            for override in args.pin:
                item = Requirement(override)
                if len(item.specifier) != 1 or next(iter(item.specifier)).operator != "==":
                    raise ValueError("--pin must be an exact package==version")
                overrides[normalize(item.name)] = next(iter(item.specifier)).version
            required = requirements()
            if not overrides.keys() <= required.keys():
                raise ValueError("Pin override is not declared by pyproject")
            pins = resolved_closure()
            for name, version in overrides.items():
                if pins[name] != version:
                    raise ValueError(
                        f"Override {name}=={version} disagrees with installed "
                        f"{name}=={pins[name]}"
                    )
            OUTPUT.write_text(render(pins), encoding="utf-8")
        check()
        print("PASS: generated development pins match pyproject.toml", flush=True)
        return 0
    except (OSError, ValueError, metadata.PackageNotFoundError) as exc:
        print(f"FAIL: development pins: {exc}", file=sys.stderr, flush=True)
        return 1


if __name__ == "__main__":
    raise SystemExit(main())
